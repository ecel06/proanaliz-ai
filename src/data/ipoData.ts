export function calculateEstimatedLots(totalShares: number, offerPrice: number, participantCount: number) {
  if (participantCount <= 0 || totalShares <= 0) return { lots: 0, cost: 0 };
  const rawLots = totalShares / participantCount;
  const lots = Math.max(1, Math.round(rawLots));
  const cost = Number((lots * offerPrice).toFixed(2));
  return { lots, cost };
}
