async function fetchBeinStandings(url) {
  try {
    const res = await fetch(url, {
      headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36' },
      signal: AbortSignal.timeout(6000)
    });
    if (!res.ok) return null;
    const html = await res.text();
    const nextDataMatch = html.match(/<script id="__NEXT_DATA__" type="application\/json">([\s\S]*?)<\/script>/);
    if (!nextDataMatch) return null;
    const data = JSON.parse(nextDataMatch[1]);
    const general = data.props?.pageProps?.data?.general;
    if (!Array.isArray(general) || general.length === 0) return null;

    return general.map((row, idx) => ({
      rank: row.position || idx + 1,
      team: row.team?.name || `Takım ${idx + 1}`,
      shortName: row.team?.abbreviation || (row.team?.name || '').slice(0, 3).toUpperCase(),
      logo: row.team?.logo || undefined,
      played: row.played || 0,
      won: row.won || 0,
      drawn: row.draw || 0,
      lost: row.lost || 0,
      gf: row.goals_scored || 0,
      ga: row.goals_against || 0,
      gd: row.goals_average !== undefined ? row.goals_average : (row.goals_scored - row.goals_against),
      points: row.point || 0,
      avgGoalsScored: row.played > 0 ? Number(((row.goals_scored || 0) / row.played).toFixed(2)) : 0,
      avgGoalsConceded: row.played > 0 ? Number(((row.goals_against || 0) / row.played).toFixed(2)) : 0,
      form: row.lastMatches ? row.lastMatches.map(m => m.displayText).filter(Boolean).slice(-5) : []
    }));
  } catch (err) {
    return null;
  }
}

async function fetchEspnStandings(leagueCode) {
  try {
    const res = await fetch(`https://site.api.espn.com/apis/v2/sports/soccer/${leagueCode}/standings`, {
      headers: { 'User-Agent': 'Mozilla/5.0' },
      signal: AbortSignal.timeout(6000)
    });
    if (!res.ok) return null;
    const data = await res.json();
    const entries = data?.children?.[0]?.standings?.entries || data?.standings?.entries || [];
    if (!Array.isArray(entries) || entries.length === 0) return null;

    return entries.map((e, idx) => {
      const getStat = (name) => {
        const found = e.stats?.find(s => s.name === name);
        return found && found.value !== undefined ? Number(found.value) : 0;
      };
      const played = getStat('gamesPlayed') || 0;
      const won = getStat('wins') || 0;
      const drawn = getStat('ties') || 0;
      const lost = getStat('losses') || 0;
      const gf = getStat('pointsFor') || 0;
      const ga = getStat('pointsAgainst') || 0;
      const gd = getStat('pointDifferential') !== undefined ? getStat('pointDifferential') : (gf - ga);
      const points = getStat('points') || 0;
      const team = e.team || {};

      return {
        rank: getStat('rank') || idx + 1,
        team: team.displayName || team.name || `Takım ${idx + 1}`,
        shortName: team.abbreviation || team.shortDisplayName || (team.displayName || '').slice(0, 3).toUpperCase(),
        logo: team.logos?.[0]?.href || undefined,
        played,
        won,
        drawn,
        lost,
        gf,
        ga,
        gd,
        points,
        avgGoalsScored: played > 0 ? Number((gf / played).toFixed(2)) : 0,
        avgGoalsConceded: played > 0 ? Number((ga / played).toFixed(2)) : 0
      };
    });
  } catch (err) {
    return null;
  }
}

function buildNormalizedResponse(leagueCode, rows) {
  const meta = LEAGUE_META[leagueCode] || { name: 'Lig Puan Durumu', country: 'Dünya', flag: '⚽' };
  const sorted = [...rows].sort((a, b) => b.points !== a.points ? b.points - a.points : b.gd - a.gd);
  const standings = sorted.map((r, i) => ({
    ...r,
    rank: i + 1,
    avgGoalsScored: r.played > 0 ? Number((r.gf / r.played).toFixed(2)) : 0,
    avgGoalsConceded: r.played > 0 ? Number((r.ga / r.played).toFixed(2)) : 0
  }));

  const espnEntries = standings.map((r) => ({
    team: {
      displayName: r.team,
      name: r.team,
      abbreviation: r.shortName,
      logos: r.logo ? [{ href: r.logo }] : []
    },
    stats: [
      { name: 'rank', value: r.rank },
      { name: 'gamesPlayed', value: r.played },
      { name: 'wins', value: r.won },
      { name: 'ties', value: r.drawn },
      { name: 'losses', value: r.lost },
      { name: 'pointsFor', value: r.gf },
      { name: 'pointsAgainst', value: r.ga },
      { name: 'pointDifferential', value: r.gd },
      { name: 'points', value: r.points }
    ]
  }));

  return {
    success: true,
    leagueCode,
    leagueName: meta.name,
    country: meta.country,
    countryFlag: meta.flag,
    seasonYear: '2026-2027',
    updatedAt: new Date().toISOString(),
    totalTeams: standings.length,
    standings,
    name: meta.name,
    children: [
      {
        standings: {
          entries: espnEntries
        }
      }
    ]
  };
}

export async function getLiveStandings(leagueCode, forceRefresh = false) {
  const now = Date.now();
  if (!forceRefresh && STANDINGS_CACHE.has(leagueCode)) {
    const cached = STANDINGS_CACHE.get(leagueCode);
    if (cached && cached.expiresAt > now) {
      return cached.data;
    }
  }

  let rows = null;

  if (leagueCode === 'tur.1') {
    rows = await fetchBeinStandings('https://beinsports.com.tr/lig/super-lig/puan-durumu');
    if (!rows || rows.length === 0) {
      rows = await fetchEspnStandings('tur.1');
    }
  } else if (leagueCode === 'tur.2') {
    rows = await fetchBeinStandings('https://beinsports.com.tr/lig/tff-1-lig/puan-durumu');
  } else {
    rows = await fetchEspnStandings(leagueCode);
  }

  if (!rows || rows.length === 0) {
    rows = VERIFIED_STANDINGS[leagueCode] || VERIFIED_STANDINGS['tur.1'] || [];
  }

  const result = buildNormalizedResponse(leagueCode, rows);

  STANDINGS_CACHE.set(leagueCode, {
    data: result,
    expiresAt: now + CACHE_TTL_MS
  });

  return result;
}
